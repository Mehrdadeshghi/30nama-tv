// Builds service/phone.js (the TizenBrew service, package.json "serviceFile") from service/src/server.js with the phone
// page service/src/page.html inlined and the app version filled in. `--check` only verifies phone.js is up to date (CI).
// Usage: node tizen-app/tools/build-service.js [--check]
var fs = require('fs'), path = require('path');
var APP = path.join(__dirname, '..'), SRC = path.join(APP, 'service', 'src'), OUT = path.join(APP, 'service', 'phone.js');
var ver = /<widget [^>]*version="([^"]*)"/.exec(fs.readFileSync(path.join(APP, 'config.xml'), 'utf8'))[1];
var page = fs.readFileSync(path.join(SRC, 'page.html'), 'utf8');
var js = fs.readFileSync(path.join(SRC, 'server.js'), 'utf8');
if (js.indexOf("'__PAGE__'") < 0 || js.indexOf("'__VERSION__'") < 0) throw new Error('placeholders missing in server.js');
var out = '/* GENERATED by tools/build-service.js from service/src/ – edit those, then rebuild. */\n' +
  js.replace("'__PAGE__'", function () { return JSON.stringify(page); }).replace("'__VERSION__'", function () { return JSON.stringify(ver); });
if (process.argv[2] === '--check') {
  var cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (cur !== out) { console.error('FAIL service/phone.js is stale: run node tizen-app/tools/build-service.js'); process.exit(1); }
  console.log('service/phone.js up to date');
} else { fs.writeFileSync(OUT, out); console.log('wrote ' + path.relative(process.cwd(), OUT) + ' (' + out.length + ' bytes, v' + ver + ')'); }
