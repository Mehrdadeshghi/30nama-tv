// Builds service/phone.js (the TizenBrew service, package.json "serviceFile") from service/src/server.js with the phone
// page service/src/page.html inlined and the app version filled in. `--check` only verifies phone.js is up to date (CI).
// Usage: node tizen-app/tools/build-service.js [--check]
var fs = require('fs'), path = require('path');
var APP = path.join(__dirname, '..'), SRC = path.join(APP, 'service', 'src'), OUT = path.join(APP, 'service', 'phone.js');
var ver = /<widget [^>]*version="([^"]*)"/.exec(fs.readFileSync(path.join(APP, 'config.xml'), 'utf8'))[1];
var page = fs.readFileSync(path.join(SRC, 'page.html'), 'utf8');
var js = fs.readFileSync(path.join(SRC, 'server.js'), 'utf8');
if (js.indexOf("'__PAGE__'") < 0 || js.indexOf("'__VERSION__'") < 0) throw new Error('placeholders missing in server.js');
var out = '/* GENERATED by tools/build-service.js from service/src/ – edit those, then rebuild. */\n' +
  js.replace("'__PAGE__'", function () { return JSON.stringify(page); }).replace("'__VERSION__'", function () { return JSON.stringify(ver); });
// The same server as the .wgt's own Tizen web service (config.xml <tizen:service>), for installs without TizenBrew:
// Tizen loads it as a module and calls onStart/onRequest/onExit.
var OUT2 = path.join(APP, 'service', 'wgt-service.js');
var out2 = '/* GENERATED by tools/build-service.js – the .wgt\'s Tizen web service (config.xml <tizen:service>). */\n' +
  'var n30started = false;\n' +
  'module.exports.onStart = function () {\n  if (n30started) return; n30started = true;\n' +
  out.split('\n').slice(1).join('\n') + '\n};\n' +
  'module.exports.onRequest = function () { module.exports.onStart(); };\n' +
  'module.exports.onExit = function () { try { process.__n30phone.server.close(); } catch (e) {} };\n';
if (process.argv[2] === '--check') {
  var cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '', cur2 = fs.existsSync(OUT2) ? fs.readFileSync(OUT2, 'utf8') : '';
  if (cur !== out || cur2 !== out2) { console.error('FAIL service/phone.js or service/wgt-service.js is stale: run node tizen-app/tools/build-service.js'); process.exit(1); }
  console.log('service files up to date');
} else {
  fs.writeFileSync(OUT, out); fs.writeFileSync(OUT2, out2);
  console.log('wrote service/phone.js + service/wgt-service.js (' + out.length + ' bytes, v' + ver + ')');
}
